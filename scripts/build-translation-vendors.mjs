#!/usr/bin/env bun
/**
 * Build the two self-contained browser ESM adapters for on-device translation.
 *
 * Tachyon publishes client/shared as standards-native ESM and does not resolve
 * bare npm specifiers, and it no longer has a postBundle hook (ADR 0052). Run this
 * before `ty bundle`: it bundles the locked `franc` detector and the
 * `@huggingface/transformers` engine into generated, git-ignored files under
 * client/shared/vendor/, which Tachyon then publishes like any shared asset.
 *
 *   /shared/vendor/translation-detection-vendor.js  (small, imported eagerly)
 *   /shared/vendor/translation-engine-vendor.js     (large, dynamically imported)
 *
 * The entry points live here, outside client/, so the browser tree never holds a
 * bare-specifier module.
 */
import { mkdir, mkdtemp, realpath, rm, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const entryRoot = await mkdtemp(join(tmpdir(), 'caduceus-translation-vendors-'))
const outputRoot = join(projectRoot, 'client', 'shared', 'vendor')

const entries = [
  {
    name: 'translation-detection-vendor.js',
    source: "export { francAll } from 'franc'\n",
  },
  {
    name: 'translation-engine-vendor.js',
    source: "export { AutoModelForSeq2SeqLM, AutoTokenizer, env, Tensor } from '@huggingface/transformers'\n",
  },
]

try {
  // Entries resolve the established dependency tree without writing into it.
  // TMPDIR controls this owned scratch location (ANNEX in the local runner).
  const dependencies = await realpath(join(projectRoot, 'node_modules'))
  await symlink(dependencies, join(entryRoot, 'node_modules'), 'junction')
  await mkdir(outputRoot, { recursive: true })
  await writeFile(join(outputRoot, '.gitignore'), '# Generated by scripts/build-translation-vendors.mjs\n*\n!.gitignore\n')

  for (const entry of entries) {
    const entryPath = join(entryRoot, entry.name)
    await writeFile(entryPath, entry.source)
    const result = await Bun.build({
      entrypoints: [entryPath],
      outdir: outputRoot,
      naming: entry.name,
      target: 'browser',
      format: 'esm',
      minify: true,
    })
    if (!result.success) {
      for (const log of result.logs) console.error(log)
      throw new Error(`Could not bundle ${entry.name}`)
    }
    // Match the generated runtime adapter to its installed package contract.
    await writeFile(join(outputRoot, entry.name.replace(/\.js$/, '.d.ts')), entry.source)
    console.log(`built client/shared/vendor/${entry.name}`)
  }
} finally {
  await rm(entryRoot, { recursive: true, force: true })
}
